-- 016（第55轮）：消息交流云端化——chat_messages / chat_business_refs 两表（PostgreSQL 等价，
-- seq 自增游标 + (sender,client_id) 幂等唯一）。运行时聊天内容只存页面隔离库，随 Red Line 永不进 Git/发行包。
-- 不做 RENAME/DO$$（WAF 教训）。
CREATE TABLE IF NOT EXISTS chat_messages(seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id text UNIQUE NOT NULL,sender text NOT NULL,recipient text NOT NULL,content text NOT NULL,client_id text NOT NULL,created_at text NOT NULL,read_at text,UNIQUE(sender,client_id));
CREATE INDEX IF NOT EXISTS chat_pair_idx ON chat_messages(sender,recipient,seq);
CREATE INDEX IF NOT EXISTS chat_unread_idx ON chat_messages(recipient,read_at);
CREATE TABLE IF NOT EXISTS chat_business_refs(message_id text PRIMARY KEY,case_id text,task_id text,driver_id text,kind text);
